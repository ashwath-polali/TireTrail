/** headline numbers as Markdown */
import type { Agreement } from '../../src/trace/agreement.ts';
import type { CityResult } from '../../src/trace/city.ts';
import { STREET_CLASSES } from '../../src/trace/streets.ts';
import { DRAIN_CLASSES } from '../../src/trace/trace.ts';

const pct = (x: number) => `${(x * 100).toFixed(1)}%`;

export function numbersMarkdown(city: CityResult, agreement: Agreement): string {
  const n = city.numbers;
  const s = city.net.stats;
  const lines: string[] = [];
  lines.push('Generated by `npm run numbers` from the app\'s own trace. Don\'t edit by hand.', '');
  lines.push('**Drains by class** (all 3,524 catch basins, manholes and inlets)', '');
  lines.push('| creek | ground | elsewhere | unknown | total |', '|---:|---:|---:|---:|---:|');
  lines.push(`| ${DRAIN_CLASSES.map((c) => n.drains.byClass[c]).join(' | ')} | ${n.drains.total} |`, '');
  const c = n.creekShare;
  const b = n.creekShareFennelBasin;
  lines.push(`- **Traceable drains reaching the creek:** ${c.creek} of ${c.traceable} (${pct(c.share)}), about **1 in ${c.oneIn}**.`);
  lines.push(`- **Inside the Fennel Creek basin:** ${b.creek} of ${b.traceable} traceable drains (${pct(b.share)}), about **1 in ${b.oneIn}** (${b.drains} drains in the basin).`);
  lines.push(`- **Unmapped:** ${n.unmapped.drains} of ${n.drains.total} drains (${pct(n.unmapped.share)}) end where the city's map stops (broken links, loops, unmapped outlets).`);
  const t = n.terrainVsPipes;
  lines.push(`- **Pipes vs terrain:** a terrain-only map sends ${pct(t.terrainCreekShare)} of Bonney Lake's street length toward Fennel Creek; by the real pipes, ${pct(t.pipesCreekShare)} of the street length with a known ending reaches it. Where both give an answer (${t.comparedKm} km of street), they disagree on ${pct(t.disagreeShare)} (${t.disagreeKm} km).`);
  lines.push(`- **Streets a terrain map sends to the creek** (${(Object.values(t.terrainCreekByPipes).reduce((x, y) => x + y, 0)).toFixed(1)} km), by where the pipes send them: ${STREET_CLASSES.map((k) => `${k} ${t.terrainCreekByPipes[k]} km`).join(', ')}.`);
  lines.push(`- **Street classes:** ${n.streets.pieces} street pieces (${n.streets.lengthKm} km), all classified: ${STREET_CLASSES.map((k) => `${k} ${n.streets.lengthKmByClass[k]} km`).join(', ')} (\`none\` = no mapped drain within 50 m).`);
  lines.push(`- **Agreement with the independent answer key:** ${pct(agreement.colorAgreement)} on the three map colors (creek / ground / grey), ${pct(agreement.classAgreement)} on all four classes.`, '');
  lines.push('**Fix list** (creek-bound endings carrying runoff from the most street length)', '');
  lines.push('| # | Ending | Street length | of which via a bridged gap | Drains |', '|---:|---|---:|---:|---:|');
  for (const f of n.fixList) {
    lines.push(`| ${f.rank} | ${f.label} | ${(f.streetM / 1000).toFixed(2)} km | ${(f.inferredStreetM / 1000).toFixed(2)} km | ${f.drains} |`);
  }
  const gaps = [...new Set(n.fixList.flatMap((f) => f.bridges))];
  if (gaps.length) lines.push('', `Gaps the city's map leaves open that these paths cross (worth confirming with the city): ${gaps.join('; ')}.`);
  lines.push('');
  lines.push('**Network**', '');
  lines.push(`- ${s.assets} assets (${s.drains} drains), ${s.links} links, of which ${s.inferredLinks} inferred where the city left an end blank (${s.linksByHow.snap + s.linksByHow['snap-mid'] + s.linksByHow['snap-pond']} snapped within 1.5 m or into a pond, ${s.linksByHow['bridge-5m'] + s.linksByHow['bridge-10m'] + s.linksByHow['bridge-pond']} bridged across a gap of up to 10 m, or 20 m into a pond).`);
  lines.push(`- ${s.components} separate network pieces, ${s.loops} loops in the city data (${s.assetsInLoops} assets), ${s.rejectedLoopBridges} bridges refused because they would have made a loop.`);
  lines.push(`- ${s.skippedNoGeometry} pipes skipped for missing geometry; ${s.duplicateIds} asset IDs used twice.`);
  return lines.join('\n');
}
