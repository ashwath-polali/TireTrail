const WORD = new RegExp(`\\b(${Object.keys(SAY).join('|')})\\b`, 'g');

/** The line as the voice should hear it: hard names respelled, the rest untouched. */
export function sayable(text: string): string {
  return text.replace(WORD, (w) => SAY[w] ?? w);
}
