export type GlyphName = keyof typeof G;
export const GLYPHS = Object.keys(G) as GlyphName[];

/** Width and height of a bitmap; rows may differ, the widest counts. */
export function bitmapSize(rows: readonly string[]): [number, number] {
  return [Math.max(0, ...rows.map((r) => r.length)), rows.length];
}

/** SVG path data for one character in a bitmap, one rect per run of it in a row. */
export function bitmapPath(rows: readonly string[], ch = 'X'): string {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== ch) { x++; continue; }
      let w = 1;
      while (row[x + w] === ch) w++;
      d += `M${x} ${y}h${w}v1h-${w}z`;
      x += w;
    }
  });
  return d;
}

/** A bitmap as crisp SVG, each bitmap pixel `scale` CSS px. colors maps a character to a fill, or to [fill, opacity]. */
export function bitmapSVG(rows: readonly string[], scale = 2, colors: Record<string, string | [string, number]> = { X: 'currentColor' }, cls = 'u-g'): string {
  const [w, h] = bitmapSize(rows);
  const paths = Object.entries(colors).map(([ch, c]) => {
    const d = bitmapPath(rows, ch), [fill, op] = typeof c === 'string' ? [c, 1] : c;
    return d ? `<path d="${d}" fill="${fill}"${op < 1 ? ` fill-opacity="${op}"` : ''}/>` : '';
  }).join('');
  return `<svg class="${cls}" viewBox="0 0 ${w} ${h}" width="${w * scale}" height="${h * scale}" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${paths}</svg>`;
}

/** A pixel icon as SVG markup; an unknown name gives an empty string. */
export function glyph(name: string, scale = 2): string {
  const rows = (G as Record<string, readonly string[]>)[name];
  if (!rows) return '';
  return bitmapSVG(rows, scale, { X: 'currentColor', o: ['currentColor', 0.45] });
}

